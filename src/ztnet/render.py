"""Render a validated network into WireGuard, nftables, NetBird-style and matrix artifacts.

Rendered files are templates: private keys are never generated or embedded.
Each host loads its own key from a root-only file via PostUp.
"""

from __future__ import annotations

import datetime as dt
import ipaddress
import json
from pathlib import Path

from .engine import matches, posture_failures, reachable_pairs
from .model import Network, Peer
from .validate import policy_expired


def _host_prefix(peer: Peer) -> str:
    addr = ipaddress.ip_address(peer.address)
    return f"{addr}/{32 if addr.version == 4 else 128}"


def _active(net: Network, today: dt.date):
    for pol in net.policies:
        try:
            if pol.enabled and not policy_expired(pol, today):
                yield pol
        except ValueError:
            continue


def wireguard_config(net: Network, peer_name: str, today: dt.date | None = None) -> str:
    today = today or dt.date.today()
    me = net.peers[peer_name]
    pairs = reachable_pairs(net, today)
    neighbours = sorted(
        {d for s, d in pairs if s == me.name} | {s for s, d in pairs if d == me.name}
    )
    prefix = net.overlay.prefixlen
    lines = [
        f"# Generated by ztnet for peer {me.name} on network {net.name}.",
        "# Template only: nothing here creates an interface until an operator installs it.",
        "[Interface]",
        f"Address = {me.address}/{prefix}",
        f"ListenPort = {net.listen_port}",
        "# The private key never leaves the host. Create it with:",
        "#   umask 077; wg genkey > /etc/wireguard/%i.key",
        "PostUp = wg set %i private-key /etc/wireguard/%i.key",
        f"PostUp = nft -f /etc/ztnet/{me.name}.nft",
        "",
    ]
    for name in neighbours:
        peer = net.peers[name]
        allowed = [_host_prefix(peer), *peer.routes] if peer.routing_peer else [_host_prefix(peer)]
        lines += [
            "[Peer]",
            f"# {peer.name} ({', '.join(peer.groups)})",
            f"PublicKey = {peer.public_key or f'<PUBLIC_KEY:{peer.name}>'}",
            f"AllowedIPs = {', '.join(allowed)}",
        ]
        if peer.endpoint:
            lines.append(f"Endpoint = {peer.endpoint}")
        lines += ["PersistentKeepalive = 25", ""]
    return "\n".join(lines).rstrip() + "\n"


def nftables_rules(net: Network, peer_name: str, today: dt.date | None = None) -> str:
    """Inbound filter for one peer's WireGuard interface. WireGuard authenticates peers;
    this table enforces which ports each authenticated peer may reach."""
    today = today or dt.date.today()
    me = net.peers[peer_name]
    rules: list[str] = []
    for pol in _active(net, today):
        for src in sorted(net.peers.values(), key=lambda p: p.name):
            if src.name == me.name or not matches(pol, src, me):
                continue
            checks = [net.posture_checks.get(n) for n in pol.posture_checks]
            if any(c is None or posture_failures(src, c) for c in checks):
                continue
            fam = "ip" if ipaddress.ip_address(src.address).version == 4 else "ip6"
            match = f"{fam} saddr {src.address}"
            if pol.protocol == "all":
                rule = f"{match} accept"
            elif pol.protocol == "icmp":
                icmp = "icmp" if fam == "ip" else "icmpv6"
                rule = f"{match} meta l4proto {icmp} accept"
            elif pol.ports:
                rule = f"{match} {pol.protocol} dport {{ {', '.join(pol.ports)} }} accept"
            else:
                rule = f"{match} meta l4proto {pol.protocol} accept"
            rules.append(f'    {rule} comment "{pol.name}: {src.name}"')
    body = "\n".join(dict.fromkeys(rules)) or "    # no inbound policy targets this peer"
    return (
        f"# Generated by ztnet for {me.name}. Load only on the host itself.\n"
        "table inet ztnet {\n"
        "  chain wg_inbound {\n"
        "    type filter hook input priority 0; policy accept;\n"
        '    iifname != "wg0" return\n'
        "    ct state established,related accept\n"
        f"{body}\n"
        '    counter drop comment "default deny"\n'
        "  }\n"
        "}\n"
    )


def netbird_policies(net: Network, today: dt.date | None = None) -> list[dict[str, object]]:
    """Policy objects shaped after NetBird's public management API.

    Groups and posture checks are referenced by name; NetBird expects IDs, so map
    names to IDs before submitting anything (this tool never calls the API)."""
    today = today or dt.date.today()
    result = []
    for pol in _active(net, today):
        result.append(
            {
                "name": pol.name,
                "description": pol.description,
                "enabled": True,
                "source_posture_checks": list(pol.posture_checks),
                "rules": [
                    {
                        "name": pol.name,
                        "enabled": True,
                        "action": "accept",
                        "bidirectional": pol.bidirectional,
                        "protocol": pol.protocol,
                        "ports": list(pol.ports),
                        "sources": list(pol.sources),
                        "destinations": list(pol.destinations),
                    }
                ],
            }
        )
    return result


def access_matrix(net: Network, today: dt.date | None = None) -> str:
    today = today or dt.date.today()
    pairs = reachable_pairs(net, today)
    names = sorted(net.peers)
    header = "| from \\ to | " + " | ".join(names) + " |"
    sep = "|---|" + "---|" * len(names)
    rows = [header, sep]
    for s in names:
        cells = ["-" if s == d else ("allow" if (s, d) in pairs else "deny") for d in names]
        rows.append(f"| {s} | " + " | ".join(cells) + " |")
    return (
        f"# Access matrix: {net.name}\n\nDefault action: {net.default_action}\n\n"
        + "\n".join(rows)
        + "\n"
    )


def mermaid_topology(net: Network, today: dt.date | None = None) -> str:
    today = today or dt.date.today()
    lines = ["flowchart LR"]
    for g in sorted(net.groups):
        lines.append(f'  subgraph {g.replace("-", "_")}["{g}"]')
        for p in net.members(g):
            lines.append(f'    {g.replace("-", "_")}__{p.name.replace("-", "_")}["{p.name}"]')
        lines.append("  end")
    if any("All" in (*p.sources, *p.destinations) for p in net.policies):
        lines.append('  All(("All peers"))')
    for pol in _active(net, today):
        arrow = "<-->" if pol.bidirectional else "-->"
        label = f"{pol.protocol} {','.join(pol.ports)}".strip()
        for s in pol.sources:
            for d in pol.destinations:
                lines.append(f'  {s.replace("-", "_")} {arrow}|"{label}"| {d.replace("-", "_")}')
    return "\n".join(lines) + "\n"


def render_all(net: Network, out_dir: str | Path, today: dt.date | None = None) -> list[Path]:
    today = today or dt.date.today()
    out = Path(out_dir)
    (out / "wireguard").mkdir(parents=True, exist_ok=True)
    (out / "nftables").mkdir(parents=True, exist_ok=True)
    written: list[Path] = []
    for name in sorted(net.peers):
        wg = out / "wireguard" / f"{name}.conf"
        wg.write_text(wireguard_config(net, name, today), encoding="utf-8")
        nft = out / "nftables" / f"{name}.nft"
        nft.write_text(nftables_rules(net, name, today), encoding="utf-8")
        written += [wg, nft]
    nb = out / "netbird-policies.json"
    nb.write_text(json.dumps(netbird_policies(net, today), indent=2) + "\n", encoding="utf-8")
    mx = out / "access-matrix.md"
    mx.write_text(access_matrix(net, today), encoding="utf-8")
    mm = out / "topology.mmd"
    mm.write_text(mermaid_topology(net, today), encoding="utf-8")
    return [*written, nb, mx, mm]
